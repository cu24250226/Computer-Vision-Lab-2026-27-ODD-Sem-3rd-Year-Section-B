import cv2
import numpy as np
import matplotlib.pyplot as plt
import os

filename = '/content/78d8d060-21ce-11f0-89a9-cb5ed9bbefd9.jpg.webp'

if not os.path.exists(filename):
    raise ValueError(f"File '{filename}' does not exist.")

img = cv2.imread(filename, cv2.IMREAD_GRAYSCALE)

if img is None:
    raise ValueError(f"Could not read '{filename}' as an image.")

rows, cols = img.shape
crow, ccol = rows // 2, cols // 2

dft = cv2.dft(np.float32(img), flags=cv2.DFT_COMPLEX_OUTPUT)
dft_shift = np.fft.fftshift(dft)

magnitude_spectrum = 20 * np.log(cv2.magnitude(dft_shift[:, :, 0], dft_shift[:, :, 1]) + 1)

radius_lp = 30
mask_lp = np.zeros((rows, cols, 2), np.uint8)
cv2.circle(mask_lp, (ccol, crow), radius_lp, (1, 1), -1)

fshift_lp = dft_shift * mask_lp
f_ishift_lp = np.fft.ifftshift(fshift_lp)
img_back_lp = cv2.idft(f_ishift_lp)
img_back_lp = cv2.magnitude(img_back_lp[:, :, 0], img_back_lp[:, :, 1])
img_back_lp = cv2.normalize(img_back_lp, None, 0, 255, cv2.NORM_MINMAX)

radius_hp = 30
mask_hp = np.ones((rows, cols, 2), np.uint8)
cv2.circle(mask_hp, (ccol, crow), radius_hp, (0, 0), -1)

fshift_hp = dft_shift * mask_hp
f_ishift_hp = np.fft.ifftshift(fshift_hp)
img_back_hp = cv2.idft(f_ishift_hp)
img_back_hp = cv2.magnitude(img_back_hp[:, :, 0], img_back_hp[:, :, 1])
img_back_hp = cv2.normalize(img_back_hp, None, 0, 255, cv2.NORM_MINMAX)

plt.figure(figsize=(12, 8))

plt.subplot(2, 2, 1)
plt.imshow(img, cmap='gray')
plt.title('Original Image')
plt.axis('off')

plt.subplot(2, 2, 2)
plt.imshow(magnitude_spectrum, cmap='gray')
plt.title('Magnitude Spectrum')
plt.axis('off')

plt.subplot(2, 2, 3)
plt.imshow(img_back_lp, cmap='gray')
plt.title('Low-Pass Filtered Image')
plt.axis('off')

plt.subplot(2, 2, 4)
plt.imshow(img_back_hp, cmap='gray')
plt.title('High-Pass Filtered Image')
plt.axis('off')

plt.tight_layout()
plt.savefig('output.png')
print("Saved output.png")

